#!/usr/bin/env python3
"""regenerate the host test fixtures from saved pikabu pages.

the core parses utf-8, so the cp1251 bytes pikabu serves are decoded here and
re-encoded once. run it against pages saved with curl, not against a live fetch,
so a test run never depends on the site being up:

    curl -sSL -o feed.html  https://pikabu.ru/
    curl -sSL -o story.html https://pikabu.ru/story/<slug>
    tools/make_fixtures.py feed.html story.html
    tools/make_fixtures.py --cards feed.html
"""

import datetime
import re
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TESTS = ROOT / "tests"


def read(path):
    return pathlib.Path(path).read_bytes().decode("cp1251")


def element(text, start, tag):
    """the whole element beginning at `start`, counting nested tags of `tag`."""
    pattern = re.compile(r"</?" + tag + r"\b")
    depth = 0
    index = start
    while index < len(text):
        match = pattern.search(text, index)
        if not match:
            raise SystemExit("unterminated <%s> at %d" % (tag, start))
        depth += -1 if match.group(0).startswith("</") else 1
        index = match.end()
        if depth == 0:
            return text[start:text.index(">", index) + 1]
    raise SystemExit("unterminated <%s>" % tag)


def find_element(text, needle, tag):
    at = text.index(needle)
    # the needle may itself be the opening tag, so include its own offset
    start = text.rindex("<" + tag, 0, at + len(tag) + 1)
    return element(text, start, tag)


def literal(name, value):
    """emit one c string literal, split per source line to stay readable"""
    out = ["static const char %s[] =" % name]
    for line in value.encode("utf-8").decode("utf-8").split("\n"):
        escaped = (line.replace("\\", "\\\\").replace('"', '\\"')
                       .replace("\t", "\\t").replace("\r", "\\r"))
        out.append('    "%s\\n"' % escaped)
    out.append("    ;")
    return "\n".join(out)


def header(source_note):
    stamp = datetime.date.today().isoformat()
    return ("/* generated by tools/make_fixtures.py on %s\n"
            "   %s\n"
            "   real markup, re-encoded from the cp1251 pikabu serves to the utf-8\n"
            "   the core parses. do not edit by hand: regenerate from a saved page. */\n"
            % (stamp, source_note))


# one real card per layout the parser has to tell apart. each predicate picks
# the first matching card on the saved page, so the fixture is whatever the site
# served when it was saved
CARD_KINDS = [
    ("pk_fixture_text_card", "text post with a community",
     lambda c: "story-block_type_text" in c and "story__community-name" in c
               and "story-block_type_video" not in c and "story-block_type_image" not in c),
    ("pk_fixture_hidden_rating_card", "rating shown only in the aria-label",
     lambda c: "story__rating-count" not in c and 'aria-label="' in c and "story__rating-block" in c),
    ("pk_fixture_video_card", "video post with player controls in the body",
     lambda c: "story-block_type_video" in c and "story-block_type_text" in c),
    ("pk_fixture_default_avatar_card", "author without an avatar picture",
     lambda c: "avatar__default" in c and "story-block_type_image" in c),
    ("pk_fixture_ad_card", "advertising slot rendered as an article",
     lambda c: "adfox" in c),
]


def make_cards(feed_path):
    feed = read(feed_path)
    cards = []
    for match in re.finditer(r'<article\b[^>]*\bclass="story[\s"]', feed):
        cards.append(element(feed, match.start(), "article"))
    parts = [header("post card layouts from https://pikabu.ru/"), ""]
    for name, _, predicate in CARD_KINDS:
        chosen = next((c for c in cards if predicate(c)), None)
        if chosen is None:
            raise SystemExit("the saved feed has no card for %s" % name)
        parts.append(literal(name, chosen))
        parts.append("")
    TESTS.joinpath("feed_cards_fixture.inc").write_text("\n".join(parts), encoding="utf-8")
    print("feed_cards_fixture.inc  %d bytes" % TESTS.joinpath("feed_cards_fixture.inc").stat().st_size)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--cards":
        make_cards(sys.argv[2])
        return
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    feed = read(sys.argv[1])
    story = read(sys.argv[2])

    card = find_element(feed, '<article class="story', "article")
    content = find_element(story, 'class="story__content-inner"', "div")
    emotions = find_element(story, 'class="story__emotions', "div")
    tree = re.search(r'<script[^>]*data-entry="comments-tree"[^>]*>.*?</script>', story, re.S).group(0)

    comments = []
    for match in re.finditer(r'<div\b[^>]*\bclass="comment(?:\s|")[^>]*>', story):
        comments.append(element(story, match.start(), "div"))
        if len(comments) == 2:
            break
    if len(comments) < 2:
        raise SystemExit("the saved story page carries fewer than two comments")

    TESTS.joinpath("feed_fixture.inc").write_text(
        header("one post card from https://pikabu.ru/") + "\n" + literal("pk_fixture_card", card) + "\n",
        encoding="utf-8")

    parts = [header("one story page from https://pikabu.ru/story/"), ""]
    parts.append(literal("pk_fixture_story_content", content))
    parts.append("")
    parts.append(literal("pk_fixture_story_emotions", emotions))
    parts.append("")
    parts.append(literal("pk_fixture_comments_tree", tree))
    for number, comment in enumerate(comments, 1):
        parts.append("")
        parts.append(literal("pk_fixture_comment_%d" % number, comment))
    TESTS.joinpath("story_fixture.inc").write_text("\n".join(parts) + "\n", encoding="utf-8")

    for name in ("feed_fixture.inc", "story_fixture.inc"):
        print("%s  %d bytes" % (name, TESTS.joinpath(name).stat().st_size))


if __name__ == "__main__":
    main()
