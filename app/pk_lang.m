BOOL PKEnglishEnabled(void) {
    NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
    if ([defaults objectForKey:PKEnglishKey]) return [defaults boolForKey:PKEnglishKey];
/* nothing chosen: a russian device keeps the source, every other one gets english */
    {
        NSArray *preferred = [NSLocale preferredLanguages];
        NSString *first = preferred.count ? [preferred objectAtIndex:0] : nil;
        return !([first isKindOfClass:[NSString class]] && [[first lowercaseString] hasPrefix:@"ru"]);
    }
}

void PKSetEnglishEnabled(BOOL enabled) {
    NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
    [defaults setBool:enabled forKey:PKEnglishKey];
    [defaults synchronize];
/* same signal as the theme, every screen already redraws from it */
    PKPostThemeChange();
}

NSString *PKLanguageName(void) {
/* each language names itself, so the row reads the same from either side */
    return PKEnglishEnabled() ? @"English" : @"Русский";
}

NSString *PKText(NSString *russian) {
    NSString *english;
    if (!russian.length || !PKEnglishEnabled()) return russian;
    english = [PKTranslations() objectForKey:russian];
    return english.length ? english : russian;
}
